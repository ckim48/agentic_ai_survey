#!/usr/bin/env python3
import argparse
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.simulator import SCHEMES


METRICS = [
    "deadline_success", "mean_latency_s", "p95_latency_s", "mean_dt_age_s",
    "p95_position_error_m", "mean_rounds", "mean_rejections", "mean_tool_calls",
    "mean_planner_ms_proxy", "mean_input_tokens_proxy", "mean_output_tokens_proxy",
    "deadline_success_safety", "deadline_success_cooperative", "deadline_success_routine",
]


def summarize(df):
    out = []
    for (scheme, vehicles), g in df.groupby(["scheme", "vehicles"], sort=False):
        row = {"scheme": scheme, "vehicles": int(vehicles), "runs": int(len(g))}
        for m in METRICS:
            x = g[m].to_numpy(float)
            sd = float(x.std(ddof=1)) if len(x) > 1 else 0.0
            row[m + "_mean"] = float(x.mean())
            row[m + "_sd"] = sd
            row[m + "_ci95"] = 1.96 * sd / np.sqrt(max(len(x), 1))
        out.append(row)
    return pd.DataFrame(out)


def style():
    plt.rcParams.update({"font.size": 9, "axes.grid": True, "grid.alpha": 0.25,
                         "figure.dpi": 120, "savefig.dpi": 300})


def plot_main(s, figdir):
    style()
    colors = {"AAI-CDOS": "#0072B2", "Single Domain": "#D55E00",
              "Independent Agents": "#E69F00", "One-Shot LLM": "#009E73"}
    panels = [
        ("deadline_success", "Deadline satisfaction", 100.0, "%"),
        ("p95_latency_s", "P95 E2E latency", 1000.0, "ms"),
        ("mean_dt_age_s", "Mean DT age", 1.0, "s"),
        ("p95_position_error_m", "P95 position error", 1.0, "m"),
    ]
    fig, axes = plt.subplots(2, 2, figsize=(7.2, 5.3))
    for ax, (m, title, scale, unit) in zip(axes.ravel(), panels):
        for scheme in SCHEMES:
            g = s[s.scheme == scheme].sort_values("vehicles")
            x = g.vehicles.to_numpy()
            y = g[m + "_mean"].to_numpy() * scale
            e = g[m + "_ci95"].to_numpy() * scale
            ax.errorbar(x, y, yerr=e, marker="o", capsize=3, lw=1.6,
                        color=colors[scheme], label=scheme)
        ax.set_title(title)
        ax.set_xlabel("Connected vehicles")
        ax.set_ylabel(unit)
        ax.set_xticks(sorted(s.vehicles.unique()))
        if m != "deadline_success":
            ax.set_yscale("log")
    axes[0, 0].legend(frameon=True, fontsize=8)
    fig.tight_layout()
    os.makedirs(figdir, exist_ok=True)
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(figdir, "main_performance." + ext), bbox_inches="tight")
    plt.close(fig)


def plot_overhead(s, figdir):
    style()
    a = s[s.scheme == "AAI-CDOS"].sort_values("vehicles")
    x = np.arange(len(a)); labels = [str(v) for v in a.vehicles]
    fig, axes = plt.subplots(1, 3, figsize=(7.2, 2.55))
    axes[0].bar(x, a.mean_rounds_mean, color="#0072B2")
    axes[0].set_title("Coordination rounds")
    axes[1].bar(x, a.mean_tool_calls_mean, color="#009E73")
    axes[1].set_title("Tool calls/event")
    axes[2].bar(x, a.mean_input_tokens_proxy_mean + a.mean_output_tokens_proxy_mean,
                color="#CC79A7")
    axes[2].set_title("Token estimate/event")
    for ax in axes:
        ax.set_xticks(x); ax.set_xticklabels(labels); ax.set_xlabel("Vehicles")
    axes[2].set_ylabel("proxy tokens")
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(figdir, "agent_overhead." + ext), bbox_inches="tight")
    plt.close(fig)


def write_tex(s, outdir):
    a = s[s.scheme == "AAI-CDOS"].set_index("vehicles")
    lines = ["% Auto-generated by scripts/summarize_results.py"]
    for n, r in a.iterrows():
        lines.append("\\newcommand{\\AAISuccess%d}{%.1f\\%%}" %
                     (n, 100.0 * r["deadline_success_mean"]))
        lines.append("\\newcommand{\\AAIPNLatency%d}{%.1f}" %
                     (n, 1000.0 * r["p95_latency_s_mean"]))
        lines.append("\\newcommand{\\AAIAge%d}{%.3f}" %
                     (n, r["mean_dt_age_s_mean"]))
    with open(os.path.join(outdir, "results_autofill.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")


def write_results_table(s, outdir):
    lines = [
        "% Auto-generated by scripts/summarize_results.py",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\caption{Trace-driven Seoul V2X performance (mean $\\pm$ 95\\% CI over 30 seeds).}",
        "  \\label{tab:aai_cdos_results}",
        "  \\begin{tabular}{c|l|c|c|c|c}",
        "    \\hline",
        "    Vehicles & Scheme & Deadline (\\%) & P95 latency (ms) & Mean DT age (s) & P95 error (m) \\\\",
        "    \\hline",
    ]
    for n in sorted(s.vehicles.unique()):
        block = s[s.vehicles == n].set_index("scheme")
        for i, scheme in enumerate(SCHEMES):
            r = block.loc[scheme]
            vals = [
                "$%.2f \\pm %.2f$" % (100 * r.deadline_success_mean, 100 * r.deadline_success_ci95),
                "$%.1f \\pm %.1f$" % (1000 * r.p95_latency_s_mean, 1000 * r.p95_latency_s_ci95),
                "$%.3f \\pm %.3f$" % (r.mean_dt_age_s_mean, r.mean_dt_age_s_ci95),
                "$%.1f \\pm %.1f$" % (r.p95_position_error_m_mean, r.p95_position_error_m_ci95),
            ]
            if scheme == "AAI-CDOS":
                vals = ["\\textbf{%s}" % x for x in vals]
            first = str(int(n)) if i == 0 else ""
            lines.append("    %s & %s & %s \\\\" % (first, scheme, " & ".join(vals)))
        lines.append("    \\hline")
    lines += ["  \\end{tabular}", "\\end{table*}"]
    with open(os.path.join(outdir, "results_table.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")


def write_summary_md(s, outdir):
    lines = ["# Full experiment summary", "",
             "Thirty independent seeds, 180 nonempty Seoul-Gangnam V2X snapshots per run,",
             "and 95% confidence intervals. Planner overhead columns are local proxies, not GPT-4o telemetry.", ""]
    for n in sorted(s.vehicles.unique()):
        g = s[s.vehicles == n].set_index("scheme")
        a = g.loc["AAI-CDOS"]
        b = g.drop(index="AAI-CDOS")
        best_success = b.deadline_success_mean.max()
        best_p95 = b.p95_latency_s_mean.min()
        best_age = b.mean_dt_age_s_mean.min()
        lines += [
            "## %d vehicles" % n, "",
            "- AAI-CDOS deadline satisfaction: %.2f%% +/- %.2f percentage points (95%% CI)." %
            (100 * a.deadline_success_mean, 100 * a.deadline_success_ci95),
            "- Gain over the strongest baseline: %.2f percentage points." %
            (100 * (a.deadline_success_mean - best_success)),
            "- P95 latency: %.1f ms (%.1f%% below the lowest-latency baseline)." %
            (1000 * a.p95_latency_s_mean, 100 * (1 - a.p95_latency_s_mean / best_p95)),
            "- Mean DT age: %.3f s (%.1f%% below the best baseline)." %
            (a.mean_dt_age_s_mean, 100 * (1 - a.mean_dt_age_s_mean / best_age)), "",
        ]
    lines += ["## Guardrail", "",
              "The Seoul source provides mobility only. Radio/network/compute states are simulated,",
              "and the 80-ms independent-agent reconciliation delay is an explicit baseline assumption.",
              "Run sensitivity analysis before using causal or deployment claims."]
    with open(os.path.join(outdir, "README.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="config/simulation.yaml")
    ap.add_argument("--input")
    ap.add_argument("--output")
    args = ap.parse_args()
    cp = args.config if os.path.isabs(args.config) else os.path.join(ROOT, args.config)
    with open(cp, "r") as f:
        cfg = yaml.safe_load(f)
    inp = args.input or os.path.join(cfg["experiment"]["output_dir"], "raw_runs.csv")
    inp = inp if os.path.isabs(inp) else os.path.join(ROOT, inp)
    out = args.output or cfg["experiment"]["output_dir"]
    out = out if os.path.isabs(out) else os.path.join(ROOT, out)
    os.makedirs(out, exist_ok=True)
    s = summarize(pd.read_csv(inp))
    s.to_csv(os.path.join(out, "summary.csv"), index=False)
    figdir = os.path.join(ROOT, "figures") if os.path.basename(out) == "full" else out
    plot_main(s, figdir)
    plot_overhead(s, figdir)
    paperdir = os.path.join(ROOT, "paper")
    os.makedirs(paperdir, exist_ok=True)
    write_tex(s, paperdir)
    write_results_table(s, paperdir)
    write_summary_md(s, out)
    print(s[["scheme", "vehicles", "deadline_success_mean", "p95_latency_s_mean",
             "mean_dt_age_s_mean", "p95_position_error_m_mean"]].to_string(index=False))


if __name__ == "__main__":
    main()
